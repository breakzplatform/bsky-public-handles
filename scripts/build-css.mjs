// Bundles the joseli.to design system tokens (scripts/ds/, a verbatim copy
// from the design system: replace the directory, never edit it) into the one
// stylesheet the site links. Page-specific components stay inline in
// site/index.html. The output is committed, so Netlify needs no build step.
// Re-run after replacing scripts/ds/.
import { readFileSync, writeFileSync, mkdirSync } from "node:fs";

// Same order as scripts/ds/styles.css.
const tokens = ["fonts", "colors", "dark", "terminal", "typography", "spacing", "borders", "halftone", "base", "neo"];
const output = "site/assets/ds.css";

const header = "/* Generated by scripts/build-css.mjs from the joseli.to design system. Do not edit. */\n";
const css = tokens.map((name) => readFileSync(`scripts/ds/tokens/${name}.css`, "utf8").trim()).join("\n");

// The project's ink, the one place it is set: the page and the share image
// follow it (favicon.svg repeats the light value). Blue belongs to notx.blue
// itself, so this site takes magenta. It sits on `:root, [data-theme]` after
// the tokens, so it beats each theme block's default and resolves to that
// theme's magenta.
const projectInk = `:root, [data-theme] {
--project-ink:var(--ink-magenta);
--project-ink-contrast:var(--on-magenta);
}`;

mkdirSync("site/assets", { recursive: true });
writeFileSync(output, header + css + "\n" + projectInk + "\n");
console.log(output);
